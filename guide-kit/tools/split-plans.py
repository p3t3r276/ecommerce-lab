#!/usr/bin/env python3
"""Split the two lab plans into small slices so agents read only what they need.

Usage:  python3 tools/split-plans.py            (run from the kit root)

Inputs  (read-only):
  plans/source/implement-plan-v3.md
  plans/source/detail-plan.md

Outputs (regenerated every run, never edit by hand):
  plans/v3/NN-<slug>.md            one file per "## " section of v3
  plans/v3/domain/<slug>.md        domain model split per bounded context (+ events.md)
  plans/v3/steps/sN.md             roadmap bullets + gate of each step S0..S8
  plans/detail/00-<slug>.md        intro sections of the Detail Plan
  plans/detail/testing/NN-<slug>.md  testing guide split per "### "
  plans/detail/sN/_step.md         step intro (goal + gate) of the Detail Plan
  plans/detail/sN/wNN.md           one file per week (goal + session table)
  plans/index.json                 steps -> weeks -> sessions, with file paths
  plans/sessions.tsv               one line per session (buổi)
"""
from __future__ import annotations

import json
import re
import shutil
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "plans" / "source"
V3 = SRC / "implement-plan-v3.md"
DETAIL = SRC / "detail-plan.md"
OUT_V3 = ROOT / "plans" / "v3"
OUT_D = ROOT / "plans" / "detail"


def slug(text: str, max_len: int = 40) -> str:
    text = text.replace("đ", "d").replace("Đ", "D")
    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c))
    text = re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-").lower()
    return text[:max_len].rstrip("-") or "section"


def split_by_heading(lines: list[str], prefix: str) -> list[tuple[str, list[str]]]:
    """Split on lines starting with `prefix` (e.g. '## '), ignoring fenced code blocks.
    Returns [(heading_text, lines_including_heading)]. Text before the first heading
    is returned with heading_text ''."""
    parts: list[tuple[str, list[str]]] = [("", [])]
    in_code = False
    for line in lines:
        if line.lstrip().startswith("```"):
            in_code = not in_code
        if not in_code and line.startswith(prefix) and not line.startswith(prefix + "#"):
            parts.append((line[len(prefix):].strip(), [line]))
        else:
            parts[-1][1].append(line)
    return parts


def split_by_bold(lines: list[str], pattern: re.Pattern) -> list[tuple[str, list[str]]]:
    parts: list[tuple[str, list[str]]] = [("", [])]
    in_code = False
    for line in lines:
        if line.lstrip().startswith("```"):
            in_code = not in_code
        m = None if in_code else pattern.match(line)
        if m:
            parts.append((m.group(1).strip(), [line]))
        else:
            parts[-1][1].append(line)
    return parts


def write(path: Path, header: str, body: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = header + "".join(body).strip("\n") + "\n"
    path.write_text(text, encoding="utf-8")


def src_note(src: Path, heading: str) -> str:
    return f"<!-- generated by tools/split-plans.py from {src.name} › {heading} — do not edit -->\n\n"


def split_v3() -> dict:
    lines = V3.read_text(encoding="utf-8").splitlines(keepends=True)
    sections = split_by_heading(lines, "## ")
    files = {}
    steps = {}
    for i, (heading, body) in enumerate(sections):
        if not heading:
            continue
        name = f"{i:02d}-{slug(heading)}.md"
        write(OUT_V3 / name, src_note(V3, heading), body)
        files[heading] = f"plans/v3/{name}"

        if heading.startswith("Domain model"):
            bold = re.compile(r"^\*\*([^*]+)\*\*")
            for sub, sub_body in split_by_bold(body, bold):
                if not sub:
                    continue
                key = "events" if sub.lower().startswith("integration event") else slug(sub.split("(")[0])
                write(OUT_V3 / "domain" / f"{key}.md", src_note(V3, f"{heading} › {sub}"), sub_body)

        if heading.startswith("Lộ trình"):
            step_re = re.compile(r"^\*\*(S\d)\.\s*[^*]+\*\*")
            for sub, sub_body in split_by_bold(body, step_re):
                if not sub:
                    continue
                sid = sub.lower()
                write(OUT_V3 / "steps" / f"{sid}.md", src_note(V3, f"{heading} › {sub}"), sub_body)
                steps[sub] = f"plans/v3/steps/{sid}.md"
    return {"sections": files, "steps": steps}


WEEK_RE = re.compile(r"^Tuần\s+(\d+)\s*·\s*(.+)$")
STEP_RE = re.compile(r"^(S\d)\.\s*(.+?)\s*\(tuần\s*(\d+)\s*[–-]\s*(\d+)\)")
ROW_RE = re.compile(r"^\|\s*(\d+)\s*\|\s*((?:T[2-7]|CN)\s+[0-9/]+)\s*\|\s*(.*?)\s*\|")


def split_detail() -> dict:
    lines = DETAIL.read_text(encoding="utf-8").splitlines(keepends=True)
    sections = split_by_heading(lines, "## ")
    index: dict = {"intro": {}, "testing": {}, "steps": {}}
    sessions: list[dict] = []
    intro_no = 0
    for heading, body in sections:
        if not heading:
            continue
        m = STEP_RE.match(heading)
        if not m:
            if heading.startswith("Hướng dẫn kiểm thử"):
                subs = split_by_heading(body, "### ")
                head_name = "00-overview.md"
                write(OUT_D / "testing" / head_name, src_note(DETAIL, heading), subs[0][1])
                index["testing"]["overview"] = f"plans/detail/testing/{head_name}"
                for j, (sub, sub_body) in enumerate(subs[1:], start=1):
                    name = f"{j:02d}-{slug(sub)}.md"
                    write(OUT_D / "testing" / name, src_note(DETAIL, f"{heading} › {sub}"), sub_body)
                    index["testing"][sub] = f"plans/detail/testing/{name}"
            else:
                name = f"00-{intro_no}-{slug(heading)}.md"
                intro_no += 1
                write(OUT_D / name, src_note(DETAIL, heading), body)
                index["intro"][heading] = f"plans/detail/{name}"
            continue

        sid, title, w_from, w_to = m.group(1), m.group(2), int(m.group(3)), int(m.group(4))
        sdir = OUT_D / sid.lower()
        subs = split_by_heading(body, "### ")
        write(sdir / "_step.md", src_note(DETAIL, heading), subs[0][1])
        step = {"title": title, "weeks_declared": [w_from, w_to],
                "intro": f"plans/detail/{sid.lower()}/_step.md", "weeks": {}}
        for sub, sub_body in subs[1:]:
            wm = WEEK_RE.match(sub)
            if not wm:
                name = f"x-{slug(sub)}.md"
                write(sdir / name, src_note(DETAIL, f"{heading} › {sub}"), sub_body)
                continue
            wno, dates = int(wm.group(1)), wm.group(2).strip()
            wid = f"w{wno:02d}"
            write(sdir / f"{wid}.md", src_note(DETAIL, f"{heading} › {sub}"), sub_body)
            rows = []
            for line in sub_body:
                rm = ROW_RE.match(line)
                if rm:
                    rows.append(int(rm.group(1)))
                    sessions.append({"session": int(rm.group(1)), "step": sid, "week": wid,
                                     "day": rm.group(2), "task": rm.group(3)})
            step["weeks"][wid] = {"dates": dates, "file": f"plans/detail/{sid.lower()}/{wid}.md",
                                  "sessions": rows}
        index["steps"][sid] = step
    return {"index": index, "sessions": sessions}


def check(detail: dict) -> list[str]:
    problems = []
    nums = [s["session"] for s in detail["sessions"]]
    if nums != list(range(1, len(nums) + 1)):
        problems.append("session numbers are not a continuous 1..N sequence")
    for sid, step in detail["index"]["steps"].items():
        declared = list(range(step["weeks_declared"][0], step["weeks_declared"][1] + 1))
        found = [int(w[1:]) for w in step["weeks"]]
        if found != declared:
            problems.append(f"{sid}: heading says weeks {declared[0]}-{declared[-1]} but found {found}")
        for wid, w in step["weeks"].items():
            if len(w["sessions"]) != 4:
                problems.append(f"{sid} {wid}: {len(w['sessions'])} sessions (expected 4)")
    return problems


def main() -> int:
    for f in (V3, DETAIL):
        if not f.exists():
            print(f"Missing {f.relative_to(ROOT)}", file=sys.stderr)
            return 1
    for d in (OUT_V3, OUT_D):
        if d.exists():
            shutil.rmtree(d)
    v3 = split_v3()
    detail = split_detail()
    index = {"v3": v3, "detail": detail["index"]}
    (ROOT / "plans" / "index.json").write_text(json.dumps(index, ensure_ascii=False, indent=2), encoding="utf-8")
    with (ROOT / "plans" / "sessions.tsv").open("w", encoding="utf-8") as f:
        f.write("session\tstep\tweek\tday\ttask\n")
        for s in detail["sessions"]:
            f.write(f"{s['session']}\t{s['step']}\t{s['week']}\t{s['day']}\t{s['task']}\n")

    steps = detail["index"]["steps"]
    print(f"v3: {len(v3['sections'])} sections, {len(v3['steps'])} steps")
    print(f"detail: {len(steps)} steps, {sum(len(s['weeks']) for s in steps.values())} weeks, "
          f"{len(detail['sessions'])} sessions")
    problems = check(detail)
    for p in problems:
        print("WARNING:", p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
