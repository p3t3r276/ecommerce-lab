#!/usr/bin/env bash
# Assemble the weekly guides of a step into one file in the user's repo, as the plan expects:
#   $SHOPLAB_PATH/docs/guides/ShopLab-SN.md
# Content: the weekly guides (guides/sN/wNN.md, in order) + the "3. Contracts" section of design/sN.md
# (endpoints, events, error codes of the step). The file is generated: re-run after new guides are written.
#
#   bash tools/export-guide.sh S3
#   bash tools/export-guide.sh S3 --stdout    print instead of writing
set -euo pipefail
cd "$(dirname "$0")/.."
shopt -s nullglob

step="${1:-}"; mode="${2:-}"
[[ $step =~ ^[Ss][0-8]$ ]] || { echo "Usage: bash tools/export-guide.sh S0..S8 [--stdout]" >&2; exit 1; }
up=$(echo "$step" | tr 's' 'S'); low=$(echo "$step" | tr 'S' 's')

weeks=(guides/$low/w*.md)
[ ${#weeks[@]} -gt 0 ] || { echo "No guides in guides/$low/ yet (run /write-guides)" >&2; exit 1; }

strip_fm() { awk 'NR==1 && /^---$/ {fm=1; next} fm && /^---$/ {fm=0; next} !fm {print}' "$1"; }

build() {
  echo "<!-- Generated by guide-kit tools/export-guide.sh on $(date +%F). Do not edit here: edit the kit and re-export. -->"
  echo
  echo "# ShopLab · $up"
  echo
  echo "Gồm ${#weeks[@]} tuần hướng dẫn và phần contract của bước (endpoint, event, mã lỗi)."
  echo
  for w in $(printf '%s\n' "${weeks[@]}" | sort); do
    strip_fm "$w"; echo; echo
  done
  if [ -f "design/$low.md" ]; then
    echo "---"; echo
    echo "## Phụ lục: contract của bước $up (từ design/$low.md)"
    echo
    awk '/^## 3\. Contracts/{on=1; next} on && /^## [0-9]+\./{on=0} on {print}' "design/$low.md"
  fi
}

if [ "$mode" = "--stdout" ]; then build; exit 0; fi

[ -f kit.env ] || { echo "Missing kit.env (copy kit.env.example and set SHOPLAB_PATH)" >&2; exit 1; }
# shellcheck disable=SC1091
source kit.env
target="${SHOPLAB_PATH:?SHOPLAB_PATH not set in kit.env}"
[ -d "$target" ] || { echo "$target does not exist" >&2; exit 1; }
mkdir -p "$target/docs/guides"
out="$target/docs/guides/ShopLab-$up.md"
build > "$out"
echo "Wrote $out ($(wc -w < "$out") words, ${#weeks[@]} week(s))"
